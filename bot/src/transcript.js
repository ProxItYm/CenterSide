'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');

const { escapeHtml } = require('./knowledge');
const { transcriptDir } = require('./config');

const MAX_MESSAGES = 1000;

async function fetchAll(channel) {
  const collected = [];
  let before;
  while (collected.length < MAX_MESSAGES) {
    const batch = await channel.messages.fetch({ limit: 100, before });
    if (!batch.size) break;
    collected.push(...batch.values());
    before = batch.last().id;
    if (batch.size < 100) break;
  }
  return collected.sort((a, b) => a.createdTimestamp - b.createdTimestamp);
}

function renderHtml(channel, ticket, messages, guildName) {
  const rows = messages.map((message) => {
    const author = escapeHtml(message.author.tag || message.author.username);
    const time = new Date(message.createdTimestamp).toISOString().replace('T', ' ').slice(0, 19);
    const body = escapeHtml(message.cleanContent || message.content || '')
      .replace(/\n/g, '<br />');
    const attachments = [...message.attachments.values()]
      .map((a) => `<a class="file" href="${escapeHtml(a.url)}" target="_blank" rel="noreferrer">${escapeHtml(a.name)}</a>`)
      .join(' ');
    const staff = message.author.bot ? 'bot' : '';
    return `<article class="msg ${staff}">
  <header><span class="author">${author}</span><time>${time}</time></header>
  <div class="body">${body || '<em>[no text]</em>'}${attachments ? `<div class="files">${attachments}</div>` : ''}</div>
</article>`;
  }).join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(guildName)} — ticket #${ticket.number}</title>
<style>
  :root{color-scheme:dark}
  body{margin:0;padding:40px 20px;background:#070d1c;color:#e9f2ff;font:15px/1.6 "Segoe UI",system-ui,sans-serif}
  main{max-width:880px;margin:0 auto}
  h1{font-size:22px;letter-spacing:-.01em;margin:0 0 4px}
  .meta{color:#8ea4c6;font-size:13px;margin:0 0 28px}
  .msg{background:#0d1a33;border:1px solid rgba(120,180,255,.13);border-radius:10px;padding:14px 16px;margin-bottom:10px}
  .msg.bot{border-color:rgba(37,217,255,.35)}
  .msg header{display:flex;gap:10px;align-items:baseline;margin-bottom:6px}
  .author{font-weight:600;color:#bfe9ff}
  time{font-size:11.5px;color:#6d82a6}
  .body{white-space:pre-wrap;word-wrap:break-word}
  .files{margin-top:8px;display:flex;gap:10px;flex-wrap:wrap}
  .file{font-size:12.5px;color:#5fffe0}
  footer{margin-top:32px;font-size:12px;color:#6d82a6}
</style>
</head>
<body>
<main>
  <h1>${escapeHtml(guildName)} — ticket #${ticket.number}</h1>
  <p class="meta">
    Lane: ${escapeHtml(ticket.category)} · Opened by ${escapeHtml(ticket.userId)} ·
    Claimed by ${escapeHtml(ticket.claimedBy || '—')} ·
    ${messages.length} messages · exported ${new Date().toISOString().slice(0, 19).replace('T', ' ')} UTC
  </p>
  ${rows || '<p>No messages.</p>'}
  <footer>Transcript generated by CenterSide.</footer>
</main>
</body>
</html>`;
}

/** Reads like a chat log, not markup. This is what staff actually open. */
function renderText(messages, ticket, guildName) {
  const header = [
    `${guildName} — ticket #${ticket.number}`,
    `Lane: ${ticket.category}`,
    `Opened by: ${ticket.userId}`,
    `Claimed by: ${ticket.claimedBy || '—'}`,
    `Messages: ${messages.length}`,
    `Exported: ${new Date().toISOString().replace('T', ' ').slice(0, 19)} UTC`,
    ''.padEnd(52, '-'),
  ].join('\n');

  const lines = messages.map((message) => {
    const time = new Date(message.createdTimestamp).toISOString().slice(11, 16);
    const who = message.author.bot ? `${message.author.username} (bot)` : message.author.username;
    const body = (message.cleanContent || message.content || '').replace(/\n/g, '\n    ');
    const files = [...message.attachments.values()].map((a) => `[file] ${a.name}`).join(' ');
    return `${time}  ${who}: ${body || files ? body : '[no text]'}${files ? ` ${files}` : ''}`;
  });

  return `${header}\n${lines.join('\n')}\n`;
}

/**
 * Fetches the channel, writes a readable .txt transcript, and keeps an HTML copy
 * on disk for anything that wants to render it later.
 * Returns { text, textName, html, htmlName, count }.
 */
async function createTranscript(channel, ticket, guildName) {
  const messages = await fetchAll(channel);
  const text = renderText(messages, ticket, guildName);
  const html = renderHtml(channel, ticket, messages, guildName);
  const stamp = Date.now();
  const textName = `ticket-${ticket.number}-${stamp}.txt`;
  const htmlName = `ticket-${ticket.number}-${stamp}.html`;

  await fs.mkdir(transcriptDir, { recursive: true });
  await fs.writeFile(path.join(transcriptDir, textName), text, 'utf8').catch(() => {});
  await fs.writeFile(path.join(transcriptDir, htmlName), html, 'utf8').catch(() => {});

  return {
    text: Buffer.from(text, 'utf8'),
    textName,
    html: Buffer.from(html, 'utf8'),
    htmlName,
    count: messages.length,
  };
}

module.exports = { createTranscript, fetchAll };
